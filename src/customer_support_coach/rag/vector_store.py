"""ChromaDB persistent vector store (tested against chromadb 1.5.x)."""

import math
import re
from contextlib import contextmanager
from pathlib import Path
from typing import Any, Iterator, Sequence

import chromadb
from chromadb.config import Settings

from .models import (
    Chunk,
    EmbeddingModelMismatchError,
    InvalidInputError,
    RagError,
    VectorStoreError,
)

_COLLECTION_NAME = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{1,510}[A-Za-z0-9]$")
_BATCH = 100
_PAGE = 1000


@contextmanager
def _storage_errors(action: str) -> Iterator[None]:
    try:
        yield
    except RagError:
        raise
    except Exception as exc:
        raise VectorStoreError(f"ChromaDB error while {action}: {exc}") from exc


def _check_metadata(meta: dict[str, Any]) -> None:
    for key, value in meta.items():
        ok = isinstance(value, (str, bool, int)) or (
            isinstance(value, float) and math.isfinite(value)
        )
        if not isinstance(key, str) or not ok:
            raise InvalidInputError(
                f"Metadata {key!r}={value!r} is not a ChromaDB-supported scalar (str/int/float/bool)."
            )


class ChromaVectorStore:
    """One persistent collection holding chunk text, vectors and metadata.

    Embeddings are supplied by the caller (never generated by Chroma), so the
    model is fully controlled by :mod:`embeddings`. The model name is stored in
    the collection metadata and checked on every open.
    """

    def __init__(
        self,
        persist_directory: str | Path,
        collection_name: str = "support_docs",
        embedding_model_name: str = "unknown",
        distance_metric: str = "cosine",
    ):
        if not isinstance(collection_name, str) or not _COLLECTION_NAME.match(collection_name):
            raise InvalidInputError(
                "collection_name must be 3-512 chars from [A-Za-z0-9._-], "
                "starting and ending with a letter or digit."
            )
        if distance_metric not in ("cosine", "l2", "ip"):
            raise InvalidInputError("distance_metric must be 'cosine', 'l2' or 'ip'.")

        self.persist_directory = Path(persist_directory)
        self.collection_name = collection_name
        self.embedding_model_name = embedding_model_name
        self.distance_metric = distance_metric

        with _storage_errors("opening the store"):
            self.persist_directory.mkdir(parents=True, exist_ok=True)
            self._client = chromadb.PersistentClient(
                path=str(self.persist_directory),
                settings=Settings(anonymized_telemetry=False),
            )
            self._collection = self._client.get_or_create_collection(
                name=collection_name,
                configuration={"hnsw": {"space": distance_metric}},
                metadata={"embedding_model": embedding_model_name},
                embedding_function=None,  # we always pass embeddings explicitly
            )
            stored = (self._collection.metadata or {}).get("embedding_model")

        if stored is not None and stored != embedding_model_name:
            self.close()
            raise EmbeddingModelMismatchError(
                f"Collection {collection_name!r} was built with {stored!r} but "
                f"{embedding_model_name!r} was requested. Use a new collection name "
                "or persist directory, or re-ingest everything."
            )

    # ------------------------------------------------------------------ writes
    def upsert_chunks(self, chunks: Sequence[Chunk], embeddings: Sequence[Sequence[float]]) -> int:
        """Insert or overwrite chunks by id. Safe to call repeatedly."""
        if len(chunks) != len(embeddings):
            raise InvalidInputError("chunks and embeddings must have the same length.")
        ids = [c.chunk_id for c in chunks]
        if len(set(ids)) != len(ids):
            raise InvalidInputError("Duplicate chunk ids in one upsert call.")
        metadatas = []
        for c in chunks:
            if not c.text or not c.text.strip():
                raise InvalidInputError(f"Chunk {c.chunk_id!r} has empty text.")
            meta = dict(c.metadata)
            meta["embedding_model"] = self.embedding_model_name
            _check_metadata(meta)
            metadatas.append(meta)

        with _storage_errors("storing chunks"):
            for i in range(0, len(ids), _BATCH):
                self._collection.upsert(
                    ids=ids[i : i + _BATCH],
                    documents=[c.text for c in chunks[i : i + _BATCH]],
                    embeddings=[list(map(float, v)) for v in embeddings[i : i + _BATCH]],
                    metadatas=metadatas[i : i + _BATCH],
                )
        return len(ids)

    def delete_ids(self, ids: Sequence[str]) -> int:
        """Delete specific chunk ids; returns how many were requested."""
        ids = list(ids)
        if not ids:
            return 0
        with _storage_errors("deleting chunks"):
            for i in range(0, len(ids), _BATCH):
                self._collection.delete(ids=ids[i : i + _BATCH])
        return len(ids)

    def delete_document(self, doc_id: str) -> int:
        """Remove every chunk of one document (and nothing else)."""
        info = self.get_document_info(doc_id)
        return self.delete_ids(info["chunk_ids"]) if info else 0

    # ------------------------------------------------------------------- reads
    def count(self) -> int:
        with _storage_errors("counting chunks"):
            return int(self._collection.count())

    def get_document_info(self, doc_id: str) -> dict[str, Any] | None:
        """Summarise what is stored for ``doc_id`` (None if nothing)."""
        records = self._get_all(where={"doc_id": doc_id})
        if not records:
            return None
        return {
            "doc_id": doc_id,
            "filename": records[0][1].get("filename"),
            "chunk_ids": [rid for rid, _ in records],
            "content_hashes": {m.get("content_hash") for _, m in records},
            "chunk_counts": {m.get("chunk_count") for _, m in records},
        }

    def find_filename_by_hash(self, content_hash: str, exclude_doc_id: str | None = None) -> str | None:
        """Filename of another stored document with identical content."""
        for _, meta in self._get_all(where={"content_hash": content_hash}):
            if meta.get("doc_id") != exclude_doc_id:
                return meta.get("filename")
        return None

    def query(self, embedding: Sequence[float], n_results: int) -> list[dict[str, Any]]:
        """Nearest chunks, best first. Returns [] for an empty collection."""
        if n_results < 1:
            raise InvalidInputError("n_results must be at least 1.")
        total = self.count()
        if total == 0:
            return []
        with _storage_errors("querying"):
            raw = self._collection.query(
                query_embeddings=[list(map(float, embedding))],
                n_results=min(n_results, total),
                include=["documents", "metadatas", "distances"],
            )
        rows = []
        for rid, doc, meta, dist in zip(
            raw["ids"][0], raw["documents"][0], raw["metadatas"][0], raw["distances"][0]
        ):
            rows.append({"id": rid, "document": doc, "metadata": dict(meta or {}), "distance": float(dist)})
        return rows

    def stats(self) -> dict[str, Any]:
        """Collection summary: totals plus per-document chunk counts."""
        docs: dict[str, dict[str, Any]] = {}
        for _, meta in self._get_all():
            entry = docs.setdefault(
                str(meta.get("doc_id")),
                {"doc_id": meta.get("doc_id"), "filename": meta.get("filename"), "chunk_count": 0},
            )
            entry["chunk_count"] += 1
        documents = sorted(docs.values(), key=lambda d: str(d["filename"]).casefold())
        return {
            "collection_name": self.collection_name,
            "persist_directory": str(self.persist_directory),
            "embedding_model": self.embedding_model_name,
            "distance_metric": self.distance_metric,
            "total_chunks": sum(d["chunk_count"] for d in documents),
            "total_documents": len(documents),
            "documents": documents,
        }

    def close(self) -> None:
        """Release file handles (matters for temp-dir cleanup on Windows)."""
        try:
            self._client.close()
        except Exception:
            pass

    def __enter__(self) -> "ChromaVectorStore":
        return self

    def __exit__(self, *exc_info: object) -> None:
        self.close()

    # --------------------------------------------------------------- internals
    def _get_all(self, where: dict[str, Any] | None = None) -> list[tuple[str, dict[str, Any]]]:
        records: list[tuple[str, dict[str, Any]]] = []
        offset = 0
        with _storage_errors("reading records"):
            while True:
                page = self._collection.get(where=where, include=["metadatas"], limit=_PAGE, offset=offset)
                ids = page["ids"]
                metas = page["metadatas"] or [{}] * len(ids)
                records.extend((rid, dict(m or {})) for rid, m in zip(ids, metas))
                if len(ids) < _PAGE:
                    return records
                offset += _PAGE
